/** The guide for a route: an exact sub-page ("orders/new"), any sub-page ("orders/*"), or the section. */
export function guideKey(path, params = []) {
  if (params.length) {
    if (GUIDES[`${path}/${params[0]}`]) return `${path}/${params[0]}`;
    if (GUIDES[`${path}/*`]) return `${path}/*`;
  }
  return GUIDES[path] ? path : null;
}

const storeKey = (username) => `anbar.help.${username}`;
function seenBy(username) {
  try { return new Set(JSON.parse(localStorage.getItem(storeKey(username)) || '[]')); } catch { return new Set(); }
}
function markSeen(username, key) {
  const seen = seenBy(username);
  seen.add(key);
  try { localStorage.setItem(storeKey(username), JSON.stringify([...seen])); } catch { /* private mode */ }
}
export function resetSeen(username) {
  try { localStorage.removeItem(storeKey(username)); } catch { /* private mode */ }
}

export function openGuide(key) {
  const g = GUIDES[key];
  const list = (items) => items.map((t) => `<li>${esc(t)}</li>`).join('');
  openSheet(`آموزش: ${g.title}`, `<div class="guide">
    <p>${esc(g.intro)}</p>
    <section><h3>چه کار می‌کنید</h3><ol class="howto">${list(g.steps)}</ol></section>
    <section><h3>حواستان باشد</h3><ul class="guide-notes">${list(g.notes)}</ul></section>
    <a class="btn btn-ghost" href="#/guide">${icon('info')}همه‌ی آموزش‌ها</a>
  </div>`);
}

/** The element the shell puts above a page: a card the first time, a small button after that. */
export function helpStrip(path, params, username) {
  const key = guideKey(path, params);
  if (!key) return null;
  const g = GUIDES[key];
  const box = document.createElement('div');
  box.className = 'no-print';
  const paintButton = () => {
    box.className = 'help-link no-print';
    box.innerHTML = `<button class="btn btn-sm btn-ghost" type="button" data-help-open>${icon('info')}آموزش این بخش</button>`;
  };
  if (seenBy(username).has(key)) paintButton();
  else {
    box.className = 'help-tip no-print';
    box.innerHTML = `${icon('info')}<div class="help-tip-text"><strong>آموزش این بخش: ${esc(g.title)}</strong><p>${esc(g.intro)}</p></div>
      <div class="help-tip-actions"><button class="btn btn-sm btn-primary" type="button" data-help-open>آموزش کامل</button><button class="btn btn-sm" type="button" data-help-ok>فهمیدم</button></div>`;
  }
  box.addEventListener('click', (e) => {
    const open = e.target.closest('[data-help-open]');
    if (!open && !e.target.closest('[data-help-ok]')) return;
    markSeen(username, key);
    paintButton();
    if (open) openGuide(key);
    else $('[data-help-open]', box).focus();
  });
  return box;
}
